//! Lucide's 24-unit grid with the rulebook's stroke of 1.75 and round ends, at 16 px in rows and 14 px in bars.
//! gpui-ce draws an SVG as a mask in the element's text colour, so the stroke colour written here does not matter.

/// An interface icon.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Icon {
    /// New tab.
    Plus,
    /// Close a tab or a dialog.
    Close,
    /// A closed folder row.
    ChevronRight,
    /// An open folder row.
    ChevronDown,
    /// A folder row.
    Folder,
    /// A file row.
    File,
    /// The tools panel's toggle.
    Sidebar,
    /// Split the pane right.
    SplitRight,
    /// Split the pane down.
    SplitDown,
    /// Find.
    Search,
    /// Agents.
    Agent,
    /// Settings.
    Settings,
    /// Copy.
    Copy,
    /// Done, or a checked menu item.
    Check,
    /// Masked text.
    Hidden,
    /// Recent.
    Clock,
    /// A terminal pane.
    Terminal,
    /// Open a web address.
    ExternalLink,
    /// Copy a web address.
    Link,
    /// Paste.
    Paste,
    /// Select all.
    SelectAll,
    /// Run a command again.
    RunAgain,
    /// Agent access to a pane.
    Shield,
    /// Reset the terminal.
    Reset,
    /// Reset and clear the terminal.
    Eraser,
}

impl Icon {
    /// The icon as SVG source.
    pub fn svg(self) -> &'static [u8] {
        match self {
            Icon::Plus => PLUS,
            Icon::Close => CLOSE,
            Icon::ChevronRight => CHEVRON_RIGHT,
            Icon::ChevronDown => CHEVRON_DOWN,
            Icon::Folder => FOLDER,
            Icon::File => FILE,
            Icon::Sidebar => SIDEBAR,
            Icon::SplitRight => SPLIT_RIGHT,
            Icon::SplitDown => SPLIT_DOWN,
            Icon::Search => SEARCH,
            Icon::Agent => AGENT,
            Icon::Settings => SETTINGS,
            Icon::Copy => COPY,
            Icon::Check => CHECK,
            Icon::Hidden => HIDDEN,
            Icon::Clock => CLOCK,
            Icon::Terminal => TERMINAL,
            Icon::ExternalLink => EXTERNAL_LINK,
            Icon::Link => LINK,
            Icon::Paste => PASTE,
            Icon::SelectAll => SELECT_ALL,
            Icon::RunAgain => RUN_AGAIN,
            Icon::Shield => SHIELD,
            Icon::Reset => RESET,
            Icon::Eraser => ERASER,
        }
    }
}

